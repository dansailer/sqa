// Command go-licenses copies the licence and notice files of every Go module
// compiled into sqa (for each release GOOS/GOARCH), plus those of the Go
// toolchain itself (standard library and runtime), into one directory, so the
// release archives carry the texts the licences require.
//
//	go run ./tools/go-licenses [-o build/licenses/go] [-targets linux/amd64,windows/amd64]
//
// The output has one directory per module path, e.g.
// <out>/github.com/spf13/cobra/LICENSE.txt, and <out>/go/LICENSE for Go
// itself. It fails if a module ships no licence file.
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// licenceFile matches the files copied from a module's root directory.
var licenceFile = regexp.MustCompile(`(?i)^(licen[cs]e|copying|notice|patents)([._-].*)?$`)

type module struct {
	Path    string
	Version string
	Dir     string
	Main    bool
	Replace *module
}

type pkg struct {
	Standard bool
	Module   *module
}

func main() {
	out := flag.String("o", filepath.Join("build", "licenses", "go"), "output directory (replaced)")
	targets := flag.String("targets", "linux/amd64,windows/amd64", "comma-separated GOOS/GOARCH list")
	pkgFlag := flag.String("pkg", "./cmd/sqa", "main package")
	flag.Parse()
	if err := run(*out, strings.Split(*targets, ","), *pkgFlag); err != nil {
		fmt.Fprintln(os.Stderr, "go-licenses:", err)
		os.Exit(1)
	}
}

func run(out string, targets []string, mainPkg string) error {
	mods := map[string]module{}
	for _, t := range targets {
		goos, goarch, ok := strings.Cut(strings.TrimSpace(t), "/")
		if !ok {
			return fmt.Errorf("bad target %q, want GOOS/GOARCH", t)
		}
		if err := listModules(goos, goarch, mainPkg, mods); err != nil {
			return err
		}
	}
	goroot, err := goEnv("GOROOT")
	if err != nil {
		return err
	}
	goVersion, err := goEnv("GOVERSION")
	if err != nil {
		return err
	}
	mods["go"] = module{Path: "go", Version: goVersion, Dir: goroot}

	if err := os.RemoveAll(out); err != nil {
		return err
	}
	paths := make([]string, 0, len(mods))
	for p := range mods {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	var index strings.Builder
	index.WriteString("Go modules compiled into sqa and their licence files.\n")
	index.WriteString("Generated by tools/go-licenses; do not edit.\n\n")
	for _, p := range paths {
		m := mods[p]
		files, err := copyLicences(m.Dir, filepath.Join(out, filepath.FromSlash(m.Path)))
		if err != nil {
			return fmt.Errorf("%s: %w", m.Path, err)
		}
		if len(files) == 0 {
			return fmt.Errorf("%s %s: no licence file in %s", m.Path, m.Version, m.Dir)
		}
		fmt.Fprintf(&index, "%s %s: %s\n", m.Path, m.Version, strings.Join(files, ", "))
	}
	if err := os.WriteFile(filepath.Join(out, "MODULES.txt"), []byte(index.String()), 0o644); err != nil { //nolint:gosec // shipped in release archives, world-readable
		return err
	}
	fmt.Print(index.String())
	return nil
}

func goEnv(key string) (string, error) {
	b, err := exec.Command("go", "env", key).Output() //nolint:gosec // fixed go subcommand, key is a constant
	if err != nil {
		return "", fmt.Errorf("go env %s: %w", key, err)
	}
	return strings.TrimSpace(string(b)), nil
}

func listModules(goos, goarch, mainPkg string, mods map[string]module) error {
	cmd := exec.Command("go", "list", "-deps", "-json=Standard,Module", mainPkg) //nolint:gosec // build tool, package from the -pkg flag
	cmd.Env = append(os.Environ(), "GOOS="+goos, "GOARCH="+goarch, "CGO_ENABLED=0")
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	b, err := cmd.Output()
	if err != nil {
		return fmt.Errorf("go list (%s/%s): %w: %s", goos, goarch, err, stderr.String())
	}
	dec := json.NewDecoder(bytes.NewReader(b))
	for {
		var p pkg
		if err := dec.Decode(&p); errors.Is(err, io.EOF) {
			return nil
		} else if err != nil {
			return err
		}
		if p.Standard || p.Module == nil || p.Module.Main {
			continue
		}
		m := *p.Module
		if m.Replace != nil {
			m.Dir = m.Replace.Dir
		}
		if m.Dir == "" {
			return fmt.Errorf("%s %s: module not downloaded (run go mod download)", m.Path, m.Version)
		}
		mods[m.Path] = m
	}
}

func copyLicences(src, dst string) ([]string, error) {
	entries, err := os.ReadDir(src)
	if err != nil {
		return nil, err
	}
	var files []string
	for _, e := range entries {
		if !e.Type().IsRegular() || !licenceFile.MatchString(e.Name()) {
			continue
		}
		b, err := os.ReadFile(filepath.Join(src, e.Name())) //nolint:gosec // licence file in the Go module cache
		if err != nil {
			return nil, err
		}
		if err := os.MkdirAll(dst, 0o755); err != nil { //nolint:gosec // shipped in release archives, world-readable
			return nil, err
		}
		if err := os.WriteFile(filepath.Join(dst, e.Name()), b, 0o644); err != nil { //nolint:gosec // shipped in release archives, world-readable
			return nil, err
		}
		files = append(files, e.Name())
	}
	return files, nil
}
